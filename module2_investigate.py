# Hypergeometric test parameters:
#   M = universe size (510 genes)
#   n = number of "successes" in universe (top 30 attention genes)
#   N = number drawn (Liao top DEGs in universe)
#   k = observed overlap

M = len(final_genes_500)  # 510
